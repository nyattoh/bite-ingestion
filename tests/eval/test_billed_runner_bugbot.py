"""Regression tests for Bugbot PR#11 findings in billed_runner.py.

Bug 1: Checkpoint rewrite must preserve rate_limit status.
Bug 2: Post-restore refresh must persist updated baselines to checkpoint.

These tests call the real production code paths (_refresh_stale_baselines,
checkpoint rewrite logic via run_billed_pilot) to ensure the fixes are
actually exercised, not just test-local duplicates of the if-logic.
"""

from __future__ import annotations

import tempfile
from pathlib import Path
from unittest.mock import Mock

from bite_eval.pilot.billed_runner import (
    append_checkpoint,
    load_checkpoint,
    run_billed_pilot,
)


def test_bug1_checkpoint_rewrite_preserves_rate_limit_status() -> None:
    """Bug 1 regression: rate_limit sibling keeps rate_limit after raw_full success rewrite.
    
    Calls PRODUCTION CODE PATH: run_billed_pilot with mocked client to trigger the
    real checkpoint-rewrite logic that preserves rate_limit status (lines 832-846).
    
    Scenario:
    1. Compressed method hits rate_limit (checkpointed)
    2. raw_full succeeds on resume (calls _refresh_stale_baselines, then checkpoint rewrite)
    3. Checkpoint rewrite MUST preserve status=rate_limit for compressed row
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        checkpoint_path = Path(tmpdir) / "test_checkpoint.jsonl"
        
        # Use the instance_id that would be generated by generate_family_instances
        # for clean_local family, index 0 (first instance)
        instance_id = "clean_local-e0"
        family = "clean_local"
        
        # Step 1: Pre-populate checkpoint with compressed at rate_limit
        append_checkpoint(
            checkpoint_path,
            {
                "family": family,
                "instance_id": instance_id,
                "method": "compressed_passthrough",
                "status": "rate_limit",
                "error_type": "RateLimitError",
                "row": {
                    "instance_id": instance_id,
                    "family": family,
                    "method_id": "compressed_passthrough",
                    "Q": 0.0,
                    "Q_baseline": 0.0,
                    "recall_vis": 0.0,
                    "recall_rec": 0.0,
                    "provenance": 0.0,
                    "constraints_ok": False,
                    "T_total": None,
                    "T_prompt": None,
                    "T_completion": None,
                    "T_cached": None,
                    "estimate_source": "provider_usage",
                    "error": "RateLimitError: 429",
                    "baseline_status": "rate_limit",
                },
            },
        )
        
        # Step 2: Mock client returns successful raw_full (triggers production rewrite path)
        # Need to provide a real dict for usage since production code accesses .get()
        class MockResponse:
            text = "correct_answer"
            model = "test-model"
            
            @property
            def usage(self):
                return {
                    "prompt_tokens": 100,
                    "completion_tokens": 50,
                    "total_tokens": 150,
                    "cached_tokens": 0,
                }
        
        mock_client = Mock()
        mock_client.model = "test-model"
        mock_client.chat_completion.return_value = MockResponse()
        
        # Run billed pilot with resume=True: loads rate_limit row, then calls raw_full
        # Production code at lines 822-846 refreshes baselines + rewrites checkpoint
        # with the REAL status-mapping logic that preserves rate_limit
        run_billed_pilot(
            client=mock_client,
            families=[family],
            n_per_family=1,
            methods=["raw_full"],  # Only raw_full to trigger rewrite of compressed
            checkpoint_path=checkpoint_path,
            resume=True,
            stop_on_rate_limit=False,
        )
        
        # Step 3: Verify checkpoint rewrite preserved rate_limit status
        latest = load_checkpoint(checkpoint_path)
        key = (family, instance_id, "compressed_passthrough")
        assert key in latest, "Compressed row should be in checkpoint after rewrite"
        
        rec = latest[key]
        assert rec["status"] == "rate_limit", (
            f"Bug 1 regression: status should be 'rate_limit', got '{rec['status']}'. "
            f"Production checkpoint rewrite (lines 832-846) must preserve rate_limit status."
        )
        assert rec["row"]["baseline_status"] == "rate_limit"
        assert rec["row"]["error"] is not None  # error field is non-null
        
        print("✓ Bug 1 test passed: production checkpoint rewrite preserved rate_limit status")


def test_bug2_restore_refresh_persists_to_checkpoint() -> None:
    """Bug 2 regression: Post-restore baseline refresh must persist to checkpoint.
    
    Calls PRODUCTION CODE PATH: _refresh_stale_baselines + run_billed_pilot restore
    logic (lines 658-686) which persists refreshed compressed rows to checkpoint.
    
    Scenario:
    1. Compressed succeeds with stale Q_baseline=0.0, baseline_status=timeout (checkpointed)
    2. Raw_full succeeds with Q=0.85 (checkpointed)
    3. On restore-only resume (no new calls), post-restore refresh (line 662) updates
       compressed Q_baseline and constraints in memory via _refresh_stale_baselines
    4. Production code (lines 664-686) MUST persist updated compressed row to checkpoint
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        checkpoint_path = Path(tmpdir) / "test_checkpoint.jsonl"
        
        # Use the instance_id that would be generated by generate_family_instances
        # for adversarial_omission family, index 0 (first instance)
        instance_id = "adversarial_omission-e0"
        family = "adversarial_omission"
        
        # Step 1: Pre-populate checkpoint with compressed row (stale baseline)
        append_checkpoint(
            checkpoint_path,
            {
                "family": family,
                "instance_id": instance_id,
                "method": "compressed_passthrough",
                "status": "ok",
                "row": {
                    "instance_id": instance_id,
                    "family": family,
                    "method_id": "compressed_passthrough",
                    "Q": 0.90,
                    "Q_baseline": 0.0,  # Stale baseline
                    "recall_vis": 0.50,
                    "recall_rec": 0.90,
                    "provenance": 0.95,
                    "constraints_ok": False,  # Wrong due to stale baseline
                    "T_total": 1200,
                    "T_prompt": 800,
                    "T_completion": 400,
                    "T_cached": 0,
                    "estimate_source": "provider_usage",
                    "error": None,
                    "baseline_status": "timeout",  # Stale status
                },
            },
        )
        
        # Step 2: Write successful raw_full to checkpoint
        append_checkpoint(
            checkpoint_path,
            {
                "family": family,
                "instance_id": instance_id,
                "method": "raw_full",
                "status": "ok",
                "row": {
                    "instance_id": instance_id,
                    "family": family,
                    "method_id": "raw_full",
                    "Q": 0.85,
                    "Q_baseline": 0.85,  # Self-pairing
                    "recall_vis": 0.52,
                    "recall_rec": 0.91,
                    "provenance": 0.96,
                    "constraints_ok": True,
                    "T_total": 2400,
                    "T_prompt": 1600,
                    "T_completion": 800,
                    "T_cached": 0,
                    "estimate_source": "provider_usage",
                    "error": None,
                    "baseline_status": "ok",
                },
            },
        )
        
        # Step 3: Mock client (should not be called if all keys are already ok)
        class MockResponse:
            text = "test_answer"
            model = "test-model"
            
            @property
            def usage(self):
                return {
                    "prompt_tokens": 100,
                    "completion_tokens": 50,
                    "total_tokens": 150,
                    "cached_tokens": 0,
                }
        
        mock_client = Mock()
        mock_client.model = "test-model"
        mock_client.chat_completion.return_value = MockResponse()
        
        # Run billed pilot with resume=True, both methods marked "ok" in checkpoint
        # Production code at lines 658-686 will:
        # - Restore both rows into state.results (both are status=ok, so skipped for new calls)
        # - Call _refresh_stale_baselines (line 662) to update compressed in memory
        # - Persist refreshed compressed rows to checkpoint (lines 664-686)
        run_billed_pilot(
            client=mock_client,
            families=[family],
            n_per_family=1,  # Will match the restored instance from checkpoint
            methods=["raw_full", "compressed_passthrough"],
            checkpoint_path=checkpoint_path,
            resume=True,
            stop_on_rate_limit=False,
        )
        
        # Step 4: Verify updated baseline was persisted to checkpoint
        latest = load_checkpoint(checkpoint_path)
        key = (family, instance_id, "compressed_passthrough")
        assert key in latest, "Compressed row should be in checkpoint"
        
        rec = latest[key]
        row = rec["row"]
        
        # Verify the post-restore refresh persisted the updated baseline
        assert row["Q_baseline"] == 0.85, (
            f"Bug 2 regression: Q_baseline should be 0.85 (from raw_full), got {row['Q_baseline']}. "
            f"Production post-restore refresh (lines 658-686) must persist updated baselines."
        )
        assert row["baseline_status"] == "ok", (
            f"Bug 2 regression: baseline_status should be 'ok', got '{row['baseline_status']}'. "
            f"Production post-restore refresh must persist updated status."
        )
        assert row["constraints_ok"] is True, (
            f"Bug 2 regression: constraints_ok should be True after baseline update, got {row['constraints_ok']}. "
            f"Production _refresh_stale_baselines + checkpoint persist must work."
        )
        
        print("✓ Bug 2 test passed: production post-restore refresh persisted to checkpoint")


